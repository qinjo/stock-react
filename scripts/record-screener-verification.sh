echo ""
echo "== 关闭工单 #11（本地日K库与一次性 bootstrap）=="
gh issue close 11 --comment "$(cat <<'EOF'
## 验收结果

实跑 `npm run bootstrap:kline`（发布 tag `2026-09-29`）：

| 项 | 值 |
|---|---|
