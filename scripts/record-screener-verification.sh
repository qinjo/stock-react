### 边界用例

- **ISO 周键跨年归属**：`2025-12-29` 与 `2026-01-02` 同属 `2026-W01`。用 UTC 计算，避免本地时区把跨年日期挪到相邻周、把周线切错。
- **当前未走完的一周会出现在周线里**：否则实时看盘时周线会滞后一周。

测试：`indicators` 从 12 项增至 23 项；前端 `IndicatorPanel` 新增 2 项。全量：后端 258 项、前端 71 项，两侧 typecheck 均干净。
EOF
