测试：新增编排 12 项（缓存命中 / 强制刷新 / 指纹失效 / 节流 / 增量失败降级 / 上海时区边界）与 `latestTradeDate` 维护 2 项；前端新增缓存与刷新提示 3 项。全量：后端 **373 项**、前端 **89 项**，两侧 typecheck 干净。
