### 三处实现中的判断

1. **增量入口是必填依赖**。给它一个"真实网络"的默认值，会让任何忘记注入的调用（尤其测试）**在无声中打出去十几个请求**。改成必填后，类型系统会在每一处拦住你——这个改动本身就是本票"测试不触网"要求的保障。
2. **增量失败不阻断筛选**。本地数据还在，外部源临时不可用不该让整个功能变砖；但必须在响应里如实标注 `increment.failed`，界面显示「以下结果基于库内已有数据，可能不是最新交易日」。沉默地降级比失败更危险。
3. **节流 15 分钟**。惰性刷新若无节流，休市与节假日里每次点击都会白打十几个请求——数据源不会因此更新。`refresh=true` 可忽略节流。

### 顺带修掉一个把缓存意义抹掉的问题

`latestTradeDate()` 原本走 `SELECT MAX(date) FROM bars`。`bars` 是 `WITHOUT ROWID` 且主键为 `(code, date)`，裸的 `MAX(date)` **没有可用索引**，只能全扫七百三十万行——实测约 1.5 秒，而它每次请求（**包括缓存命中**）都要调用一次。

改为读元数据、并在写入更晚的 bar 时就地维护；老库缺这项元数据时回退一次全扫并补上。效果：**缓存命中 1.51s → 0.0035s**，冷启动 9.24s → 3.59s（同一个全扫在请求路径里被调用了好几次）。

### 关于「界面显示进度」

单次 GET 请求无法流式汇报进度，因此这里做到的是"事后如实告知"：响应携带 `increment`（是否跑、快照日、写入只数、其中多少只除权、回填多少名称、耗时），界面在结果头部展示。加载态文案说明"可能比平时多约十秒（需先补齐当日行情）"。真要流式进度需要改成 SSE，超出本票范围。

测试：新增编排 12 项（缓存命中 / 强制刷新 / 指纹失效 / 节流 / 增量失败降级 / 上海时区边界）与 `latestTradeDate` 维护 2 项；前端新增缓存与刷新提示 3 项。全量：后端 **373 项**、前端 **89 项**，两侧 typecheck 干净。
