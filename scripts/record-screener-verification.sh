#!/usr/bin/env bash
# 推送提交，并补记已完成工单的验收结果后关闭它们（需 gh 已认证 + git 推送凭据）。
#
# 对应本轮「A股短线筛选器」：#9（派生指标扩展）、#11（本地日K库与 bootstrap）。
