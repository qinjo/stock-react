### 对账（`npm run verify:kline`）

- **判据一 · VWAP 恒等式**：抽样 300 只，`成交额 ÷ (成交量 × 100)` 全部落在当日 `[最低, 最高]` 区间内。这条同时约束了价、量、额三个字段的**单位与方向**——换算错一位、把「手」当「股」、因子方向搞反，都会立刻越界。
- **判据二 · 跨日价格**：8 只跨板块标的（沪主板 / 深主板 / 创业板 / 科创板 / 北交所）的腾讯快照「昨收」与库内 2026-09-29 收盘**逐只精确相等**。

### 两处过程记录（供后续参考）

1. 首次对账全部报「不一致」，原因是**比错了对象**：今日是 2026-09-30，却拿库内 09-29 的 bar 去比快照 09-30 的盘中价。改为「快照昨收 ↔ 库内最新收盘」后 8/8 精确相等。
2. 刻意**没有**用腾讯日线历史做逐字段对账：那条接口返回的是**前复权**序列，与库内不复权口径不可直接比较，会在除权股上产生假不一致。

