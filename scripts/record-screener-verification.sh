| 日K行数 | 7,336,514 |
| 耗时 | 70 秒（下载 31s + 解析入库 39s） |

验收标准逐条：

- [x] 下载后校验 sha256，不匹配即失败且不写库
- [x] `.bin` 布局：元素 0 为日历起始索引、**没有数量字段**（判据 `count = 字节数 / 4 - 1`）
- [x] 清单符号大写 / features 目录小写归一化
- [x] 标的基础信息含存活标记
